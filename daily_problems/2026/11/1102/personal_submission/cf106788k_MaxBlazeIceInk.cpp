#include<bits/stdc++.h>
using namespace std;

vector<int> A[12];
vector<double> G[12];

#define MAXN 100005

int n,x[MAXN],y[MAXN],f[1 << 8],pre[1 << 8];

signed main(){
	A[0] = {0,1};
	G[0] = {-2000,0.9,0.1,0.9,0.1,2000,-2000,2000};
	A[1] = {1,2};
	G[1] = {-0.1,0.9,2000,0.9,2000,2000,-0.1,2000};
	A[2] = {2,3};
	G[2] = {0.9,-0.1,2000,-0.1,2000,2000,0.9,2000};
	A[3] = {3,4};
	G[3] = {0.9,-2000,2000,-2000,2000,0.1,0.9,0.1};
	A[4] = {4,5};
	G[4] = {-0.1,-0.9,-0.1,-2000,2000,-2000,2000,-0.9};
	A[5] = {5,6};
	G[5] = {0.1,-0.9,0.1,-2000,-2000,-2000,-2000,-0.9};
	A[6] = {6,7};
	G[6] = {-0.9,0.1,-0.9,-2000,-2000,-2000,-2000,0.1};
	A[7] = {7,0};
	G[7] = {-0.9,-0.1,-2000,-0.1,-2000,2000,-0.9,2000};
	A[8] = {0,1,2};
	G[8] = {-2000,0.9,-2000,2000,2000,2000,2000,0.9};
	A[9] = {2,3,4};
	G[9] = {0.9,2000,2000,-2000,2000,2000,0.9,-2000};
	A[10] = {4,5,6};
	G[10] = {-2000,-0.9,-2000,-2000,2000,-2000,2000,-0.9};
	A[11] = {6,7,0};
	G[11] = {-0.9,2000,-2000,-2000,-2000,2000,-0.9,-2000};
	scanf("%d",&n);
	int SS = 0;
	for( int i = 1 ; i <= n ; i ++ ){
		scanf("%d%d",&x[i],&y[i]);
		//用 xor 是人类吗
		if( x[i] < 0 && y[i] > 0 ) SS |= 1 << 0;
		if( x[i] == 0 && y[i] > 0 ) SS |= 1 << 1;
		if( x[i] > 0 && y[i] > 0 ) SS |= 1 << 2;
		if( x[i] > 0 && y[i] == 0 ) SS |= 1 << 3;
		if( x[i] > 0 && y[i] < 0 ) SS |= 1 << 4;
		if( x[i] == 0 && y[i] < 0 ) SS |= 1 << 5;
		if( x[i] < 0 && y[i] < 0 ) SS |= 1 << 6;
		if( x[i] < 0 && y[i] == 0 ) SS |= 1 << 7;
	}
	for( int S = 0 ; S < 1 << 8 ; S ++ ) f[S] = 100;
	f[0] = 0;
	for( int S = 0 ; S < 1 << 8 ; S ++ ){
		for( int i = 0 ; i < 12 ; i ++ ){
			int T = 0;
			for( int ele : A[i] ) T ^= 1 << ele;
			if( ( S & T ) ) continue;
			if( f[S ^ T] > f[S] + 1 ) f[S ^ T] = f[S] + 1,pre[S ^ T] = S;
		}
	}
	cerr << SS << "\n";
	int minn = 100,now = 0;
	for( int S = 0 ; S < 1 << 8 ; S ++ ){
		if( ( S & SS ) != SS ) continue;
		if( minn > f[S] ) minn = f[S],now = S;
	}
	printf("%d\n",f[now]);
	while( now ){
		int c = now ^ pre[now];
		for( int i = 0 ; i < 12 ; i ++ ){
			int T = 0;
			for( int ele : A[i] ) T ^= 1 << ele;
			if( T == c ){
				for( double d : G[i] )
					printf("%.1lf ",d);
				puts("");
			}
		}
		now = pre[now];
	}
	return 0;
}